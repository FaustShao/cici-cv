const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const base = process.env.PREVIEW_ROOT || 'http://127.0.0.1:8770/cici-cv/';
(async () => {
 const browser = await chromium.launch({executablePath:'/usr/bin/chromium', args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 try {
  const page = await browser.newPage({viewport:{width:1280,height:850},reducedMotion:'reduce'});
  const errors = [], missing = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => {if(r.status() >= 400) missing.push(r.url());});
  await page.goto(new URL('portfolio.html',base).href,{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>window.preview && document.body.dataset.ready && !document.documentElement.dataset.releaseState,null,{timeout:150000});
  await page.locator('#map-trigger').click();
  assert.ok(await page.locator('#world-map').evaluate(e=>e.open));
  assert.equal(await page.locator('.map-location').count(),4);
  assert.equal(await page.locator('.map-location[aria-current="true"]').getAttribute('data-destination'),'portfolio');
  assert.ok(await page.locator('.map-sheet > img').evaluate(i=>i.complete && i.naturalWidth>0));
  const selection=await page.locator('#selection').innerText();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('#selection').innerText(),selection,'Map keys cannot switch the underlying work');
  await page.locator('[data-destination="portfolio"]').click();
  assert.equal(await page.locator('#world-map').evaluate(e=>e.open),false);
  await page.keyboard.press('m');
  assert.ok(await page.locator('#world-map').evaluate(e=>e.open));
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#world-map').evaluate(e=>e.open),false);
  await page.setViewportSize({width:390,height:844});
  const map=await page.locator('#map-trigger').boundingBox(),controls=await page.locator('#controls').boundingBox();
  assert.ok(map.x>=0 && map.x+map.width<=390 && map.y+map.height<controls.y,'Mobile map stays on screen above work controls');
  await page.locator('#map-trigger').tap({force:true}).catch(()=>page.locator('#map-trigger').click());
  assert.ok(await page.locator('#world-map').evaluate(e=>e.open));
  const bounds=await page.locator('#world-map').boundingBox();
  assert.ok(bounds.x>=0 && bounds.x+bounds.width<=390);
  await page.locator('#close-map').click();
  assert.equal(await page.locator('#reset-view').innerText(),'返回主页');
  await page.locator('#reset-view').click();
  await page.waitForURL(/\/cecilia-world\/hub\.html/);
  await page.waitForFunction(()=>window.designWorld && document.body.dataset.ready && !document.documentElement.dataset.releaseState,null,{timeout:150000});
  assert.equal(await page.locator('body').getAttribute('data-place'),'home');
  await page.locator('#map-trigger').click();
  assert.ok(await page.locator('#world-map').evaluate(e=>e.open),'Shared map still works on home');
  await page.locator('[data-destination="portfolio"]').click();
  await page.waitForURL(/\/cecilia-world\/index\.html/);
  await page.waitForFunction(()=>window.preview && document.body.dataset.ready && !document.documentElement.dataset.releaseState,null,{timeout:150000});
  await page.locator('#map-trigger').click();
  await page.locator('[data-destination="resume"]').click();
  await page.waitForURL(/\/cecilia-world\/hub\.html.*#resume/);
  assert.deepEqual(errors,[]);assert.deepEqual(missing,[]);
  console.log('PASS root and canonical portfolio map; current location, keyboard isolation, mobile layout; return home; shared home map and cross-section navigation.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
