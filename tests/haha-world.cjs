const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require('playwright');
const sharp = require('sharp');
const base = process.env.PREVIEW_ROOT || 'http://127.0.0.1:8765/';
(async () => {
  const manifest = JSON.parse(fs.readFileSync('assets/haha-world/manifest.json'));
  assert.equal(manifest.pages.length, 30);
  assert.deepEqual(manifest.parts.map(p => [p.start, p.count]), [[1, 9], [10, 10], [20, 11]]);
  for (const [i, page] of manifest.pages.entries()) {
    assert.equal(page.number, i + 1);
    const meta = await sharp('assets/haha-world/pages/' + String(i + 1).padStart(2, '0') + '.webp').metadata();
    assert.equal(meta.width, 2400);
    assert.ok(Math.abs(meta.width / meta.height - manifest.width / manifest.height) < .001);
  }
  const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
    const errors = [], bad = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('response', r => { if (r.status() >= 400 && !r.url().endsWith('favicon.ico')) bad.push(r.url()); });
    await page.goto(new URL('cecilia-world/haha-world.html', base).href);
    await page.waitForFunction(() => window.HAHA_READER?.state.ready, null, { timeout: 90000 });
    assert.equal(await page.evaluate(() => HAHA_READER.state.mode), 'webgl');
    assert.equal(await page.evaluate(() => HAHA_READER.sources.length), 32);
    assert.equal(await page.locator('#page-thumbnails button').count(), 30);
    assert.equal(await page.locator('#page-status').innerText(), '封面');
    assert.ok(await page.locator('#previous').isDisabled());
    await page.evaluate(() => HAHA_READER.pause());
    await page.screenshot({ path: '/tmp/haha-closed.png', timeout: 45000 });
    await page.evaluate(() => HAHA_READER.resume());
    await page.getByRole('button', { name: '下一页', exact: true }).click();
    await page.waitForFunction(() => HAHA_READER.state.page === 1 && !HAHA_READER.magazine.turning, null, { timeout: 45000 });
    assert.deepEqual(await page.evaluate(() => HAHA_READER.state.visiblePages), [1, 2]);
    await page.waitForFunction(() => HAHA_READER.state.visiblePages.every(n => HAHA_READER.loaded.has(n)), null, { timeout: 45000 });
    const imageFrame = await page.evaluate(() => HAHA_READER.backgroundFrame);
    await page.waitForFunction(n => HAHA_READER.backgroundFrame > n + 1, imageFrame);
    await page.evaluate(() => HAHA_READER.pause());
    const screenshot = await page.screenshot({ path: '/tmp/haha-spread.png', timeout: 45000 });
    const pixels = await sharp(screenshot).removeAlpha().raw().toBuffer({ resolveWithObject: true });
    function sample(x, y) { let sum = 0; for (let yy=y; yy<y+15; yy++) for(let xx=x;xx<x+25;xx++) for(let c=0;c<3;c++) sum+=pixels.data[(yy*pixels.info.width+xx)*3+c]; return sum/(15*25*3); }
    let orange = 0; for(let i=0;i<pixels.data.length;i+=3) if(pixels.data[i]>150&&pixels.data[i+1]>75&&pixels.data[i+1]<195&&pixels.data[i+2]<100) orange++;
    assert.ok(orange>3000,'Printed VI content is visible on the spread, not blank placeholder paper');
    console.log('White paper samples', sample(120,220), sample(800,220));
    assert.ok(Math.abs(sample(120,220)-sample(800,220))<35, 'Both sides remain readable, without self-shadow striping');
    await page.getByRole('button', { name: '放大', exact: true }).click();
    await page.locator('#page-zoom img').evaluate(i => i.decode());
    assert.match(await page.locator('#page-zoom img').getAttribute('src'), /02.webp$/);
    await page.locator('#page-zoom').click({ position: { x: 15, y: 100 } });
    assert.ok(!await page.locator('#page-zoom').evaluate(el => el.open));
    await page.locator('#contents-trigger').click();
    await page.locator('[data-page="19"]').click();
    await page.evaluate(() => HAHA_READER.resume());
    await page.waitForFunction(() => HAHA_READER.state.visiblePages.includes(19));
    assert.ok(await page.locator('#contents').isHidden());
    await page.evaluate(() => HAHA_READER.goTo(31));
    await page.waitForFunction(() => HAHA_READER.state.page === 31);
    assert.ok(await page.locator('#next').isDisabled());
    await page.locator('#zoom-page').click();
    await page.locator('#page-zoom img').evaluate(i => i.decode());
    assert.match(await page.locator('#page-zoom img').getAttribute('src'), /back.webp$/);
    await page.locator('#close-zoom').click();
    await page.evaluate(() => HAHA_READER.goTo(0));
    await page.waitForFunction(() => HAHA_READER.state.page === 0);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.waitForFunction(() => HAHA_READER.renderer.domElement.width > 0);
    await page.evaluate(() => HAHA_READER.pause());
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.ok(await page.locator('.book-tools').evaluate(el => { const r=el.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.bottom<=innerHeight; }));
    await page.locator('#zoom-page').click();
    await page.locator('#page-zoom img').evaluate(i => i.decode());
    assert.ok(await page.locator('#page-zoom img').evaluate(i => { const r=i.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth; }));
    await page.getByRole('button', { name: '放大原稿', exact: true }).click();
    assert.equal(await page.locator('#detail-reset').innerText(),'150%');
    await page.getByRole('button', { name: '恢复适合窗口', exact: true }).click();
    await page.screenshot({ path: '/tmp/haha-mobile-zoom.png' });
    await page.locator('#close-zoom').click();
    assert.deepEqual(errors, []); assert.deepEqual(bad, []);
    console.log('PASS: 30 original pages in part order and A4 landscape ratio; thick bound WebGL book; click flip; contents; original-page zoom and blank dismissal; back cover; mobile controls; no failed assets.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
