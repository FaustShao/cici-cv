"""Create opt-in, pixel-identical WebP alternatives; never alter source artwork."""
from pathlib import Path
from concurrent.futures import ProcessPoolExecutor, as_completed
from collections import Counter
from io import BytesIO
import hashlib, json
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
DEST=ROOT/'assets/project-lossless'
PROJECTS=('tideline','safepaw-family','dream-sentinel')
PRESERVE=json.loads((ROOT/'scripts/project-webp-preserve.json').read_text())['files']
def sha(data):return hashlib.sha256(data).hexdigest()
def convert(source):
 source=Path(source);name=source.relative_to(ROOT).as_posix();raw=source.read_bytes()
 target=DEST/source.parent.relative_to(ROOT/'assets')/(sha(name.encode())[:24]+'.webp')
 legacy=target.with_name(source.name+'.webp') if len((source.name+'.webp').encode())<=255 else None
 if not target.exists() and legacy and legacy.exists():legacy.rename(target)
 record={'source':name,'originalBytes':len(raw),'sourceSha256':sha(raw)}
 with Image.open(source) as im:
  record['width'],record['height']=im.size
  if name in PRESERVE:
   if target.exists():target.unlink()
   return {**record,'status':'original','reason':PRESERVE[name]}
  # WebP supports 8-bit channels and at most 16383 pixels per axis.
  # Unsupported originals stay intact instead of being resized or quantized.
  if im.mode not in ('RGB','RGBA','L','LA','P') or max(im.size)>16383:
   return {**record,'status':'original','reason':'format-limit'}
  gamma=im.info.get('gamma')
  if not im.info.get('icc_profile') and gamma is not None and abs(gamma-.45455)>.0001:
   return {**record,'status':'original','reason':'nonstandard-colour-profile'}
  rgba=im.convert('RGBA');pixels=rgba.tobytes();record['pixelSha256']=sha(pixels)
  existing=False
  if target.exists():
   try:
    with Image.open(target) as check:existing=(check.size==rgba.size and check.convert('RGBA').tobytes()==pixels and check.info.get('icc_profile')==im.info.get('icc_profile') and check.info.get('exif')==im.info.get('exif'))
   except OSError:pass
  if existing:encoded=target.read_bytes()
  else:
   buffer=BytesIO();options={'lossless':True,'exact':True,'method':6}
   if im.info.get('icc_profile'):options['icc_profile']=im.info['icc_profile']
   if im.info.get('exif'):options['exif']=im.info['exif']
   rgba.save(buffer,'WEBP',**options);encoded=buffer.getvalue()
  with Image.open(BytesIO(encoded)) as check:
   if check.size!=rgba.size or check.convert('RGBA').tobytes()!=pixels:
    raise RuntimeError('Pixel or alpha mismatch: '+name)
  if len(encoded)>=len(raw):
   if target.exists():target.unlink()
   return {**record,'status':'original','reason':'not-smaller'}
  target.parent.mkdir(parents=True,exist_ok=True)
  if not existing:target.write_bytes(encoded)
  return {**record,'status':'webp','target':target.relative_to(ROOT).as_posix(),'bytes':len(encoded),'sha256':sha(encoded)}
def main():
 sources=sorted(p for project in PROJECTS for p in (ROOT/'assets'/project).rglob('*.png'))
 records=[]
 with ProcessPoolExecutor(max_workers=2) as pool:
  jobs=[pool.submit(convert,str(source)) for source in sources]
  for n,job in enumerate(as_completed(jobs),1):
   records.append(job.result())
   if n%25==0:print(f'Checked {n}/{len(sources)}',flush=True)
 records.sort(key=lambda r:r['source'])
 accepted=[r for r in records if r['status']=='webp']
 report={'encoding':'lossless WebP, exact RGBA, original dimensions','files':records,'summary':{project:{'converted':sum(r['status']=='webp' for r in records if r['source'].startswith('assets/'+project+'/')),'originalBytes':sum(r['originalBytes'] for r in records if r['source'].startswith('assets/'+project+'/')),'servedBytes':sum(r.get('bytes',r['originalBytes']) for r in records if r['source'].startswith('assets/'+project+'/'))}for project in PROJECTS}}
 DEST.mkdir(parents=True,exist_ok=True);(DEST/'manifest.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
 mapping={r['source']:r['target'] for r in accepted}
 js='// Generated by scripts/prepare-project-webp.py; source artwork stays in its original folders.\n(()=>{const files='+json.dumps(mapping,ensure_ascii=False,separators=(',',':'))+';const path=value=>new URL(value.split("/").map(encodeURIComponent).join("/"),location.href).pathname;window.CeciliaImageFormats=new Map(Object.entries(files).map(([source,target])=>[path(source),path(target)]));})();\n'
 (ROOT/'project-image-formats.js').write_text(js)
 print(json.dumps({'summary':report['summary'],'keptOriginal':dict(Counter(r.get('reason') for r in records if r['status']=='original'))},ensure_ascii=False),flush=True)
if __name__=='__main__':main()
