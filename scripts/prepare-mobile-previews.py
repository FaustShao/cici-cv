"""Build smaller inline artwork for phones. Zoom uses the full published image."""
import hashlib
import json
from io import BytesIO
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/project-mobile'
OUT.mkdir(exist_ok=True)
records = json.loads((ROOT / 'assets/project-lossless/manifest.json').read_text())['files']
mapping = {}
for entry in records:
    pixels = entry['width'] * entry['height']
    if pixels <= 2_000_000:
        continue
    preserve_png = entry.get('reason') == 'browser-scaled-composite'
    if entry['status'] != 'webp' and not preserve_png and entry.get('reason') != 'format-limit':
        continue
    with Image.open(ROOT / entry['source']) as original:
        scale = min((1_800_000 / pixels) ** 0.5, 8192 / max(original.size))
        size = tuple(max(1, round(side * scale)) for side in original.size)
        preview = original.convert('RGBA').resize(size, Image.Resampling.LANCZOS)
        encoded = BytesIO()
        if preserve_png:
            preview.save(encoded, 'PNG', icc_profile=original.info.get('icc_profile'))
        else:
            preview.save(encoded, 'WEBP', lossless=True, exact=True, method=3,
                         icc_profile=original.info.get('icc_profile', b''))
        data = encoded.getvalue()
        with Image.open(BytesIO(data)) as decoded:
            if decoded.convert('RGBA').tobytes() != preview.tobytes():
                raise ValueError(entry['source'])
        extension = '.png' if preserve_png else '.webp'
        target = OUT / (hashlib.sha256(data).hexdigest()[:20] + extension)
        target.write_bytes(data)
        mapping[entry.get('target', entry['source'])] = target.relative_to(ROOT).as_posix()
        # The fourth Dream Sentinel board already ships standalone WebP exports.
        alternate = Path(entry['source']).with_suffix('.webp')
        if entry['source'].startswith('assets/dream-sentinel/3.4/') and (ROOT / alternate).is_file():
            mapping[alternate.as_posix()] = target.relative_to(ROOT).as_posix()

js = ('// Generated by scripts/prepare-mobile-previews.py\n'
      'window.CeciliaMobilePreviews = new Map(Object.entries('
      + json.dumps(mapping, ensure_ascii=False, indent=2, sort_keys=True)
      + ').map(([source, preview]) => [new URL(source.split("/").map(encodeURIComponent).join("/"), location.href).pathname, preview]));\n')
(ROOT / 'project-mobile-previews.js').write_text(js)
print(f'{len(mapping)} mobile previews verified')
